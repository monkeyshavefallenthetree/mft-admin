"use client";

import ModalPortal from "@/components/admin/ui/ModalPortal";
import { type PayrollComputed, formatDepartment, formatEmploymentType } from "@/lib/admin/hrReports";
import { toast } from "@/lib/admin/feedback";

interface WorkerLike {
  id: string;
  firstName?: string;
  lastName?: string;
  email?: string;
  department?: string;
  role?: string;
  employmentType?: string;
  hourlyRate?: number;
}

interface Props {
  worker: WorkerLike;
  payroll: PayrollComputed;
  cycleLabel: string;
  periodStart: Date;
  periodEnd: Date;
  onClose: () => void;
}

export default function HrPayslipModal({
  worker,
  payroll,
  cycleLabel,
  periodStart,
  periodEnd,
  onClose,
}: Props) {
  const workerFullName = `${worker.firstName || ""} ${worker.lastName || ""}`.trim() || "Worker";

  const handlePrint = () => {
    window.print();
  };

  const handleCopySummary = () => {
    const text = `
=== MFT WORKFORCE PAYSLIP ===
Employee: ${workerFullName} (ID: ${worker.id})
Department: ${formatDepartment(worker.department)} | Role: ${worker.role || "Operator"}
Period: ${cycleLabel} (${periodStart.toLocaleDateString()} - ${periodEnd.toLocaleDateString()})
Rate: EGP ${payroll.hourlyRate}/h
Days Worked: ${payroll.daysWorked} / ${payroll.expectedWorkDays} Expected Workdays
Total Hours: ${payroll.totalHours}h (Overtime: ${payroll.overtimeHours}h)

EARNINGS:
- Base Pay: EGP ${payroll.basePay}
- Overtime Pay (1.5x): EGP ${payroll.overtimePay}
${payroll.allowances > 0 ? `- Allowances (بدلات): EGP ${payroll.allowances}\n` : ""}${payroll.manualBonuses > 0 ? `- Bonuses (مكافآت): EGP ${payroll.manualBonuses}\n` : ""}
DEDUCTIONS:
${payroll.absencePenalty > 0 ? `- Absence Penalty (${payroll.absentDays}d): -EGP ${payroll.absencePenalty}\n` : ""}${payroll.totalLatePenaltyEgp > 0 ? `- Lateness Penalties: -EGP ${payroll.totalLatePenaltyEgp}\n` : ""}${payroll.salaryAdvances > 0 ? `- Salary Advances (سلف): -EGP ${payroll.salaryAdvances}\n` : ""}${payroll.manualDeductions > 0 ? `- Disciplinary Deductions: -EGP ${payroll.manualDeductions}\n` : ""}
-----------------------------------------
NET PAYABLE DUE: EGP ${payroll.netPayable}
Generated by MFT Admin Workforce System
=============================
    `.trim();

    void navigator.clipboard.writeText(text);
    toast.success("Payslip summary copied to clipboard");
  };

  return (
    <ModalPortal onClose={onClose}>
      <div
        className="fixed inset-0 z-[120] bg-zinc-950/60 backdrop-blur-xs flex items-center justify-center p-3 sm:p-6 overflow-y-auto animate-fade-in print:p-0 print:bg-white"
        onClick={onClose}
      >
        <div
          className="bg-white dark:bg-zinc-900 border-2 border-zinc-900 dark:border-zinc-700 shadow-2xl w-full max-w-2xl max-h-[92vh] overflow-y-auto p-6 md:p-8 animate-scale-in text-zinc-950 dark:text-zinc-100 font-mono print:border-none print:shadow-none print:max-w-none print:max-h-none print:p-8"
          onClick={(e) => e.stopPropagation()}
        >
          {/* Header */}
          <div className="flex items-start justify-between pb-4 border-b-2 border-zinc-900 dark:border-zinc-700 mb-6">
            <div>
              <div className="flex items-center gap-2">
                <span className="text-[10px] font-bold uppercase tracking-widest text-emerald-700 bg-emerald-50 dark:bg-emerald-950/40 border border-emerald-300 dark:border-emerald-800 px-2 py-0.5 rounded">
                  OFFICIAL PAY STATEMENT
                </span>
                <span className="text-[10px] text-zinc-400 font-bold uppercase">
                  CONFIDENTIAL
                </span>
              </div>
              <h3 className="text-2xl font-black font-heading uppercase tracking-wide text-zinc-950 dark:text-white mt-1">
                Employee Compensation Payslip
              </h3>
              <p className="text-xs text-zinc-500 dark:text-zinc-400 mt-0.5">
                Cycle: <strong>{cycleLabel}</strong> ({periodStart.toLocaleDateString()} – {periodEnd.toLocaleDateString()})
              </p>
            </div>
            <button
              type="button"
              onClick={onClose}
              className="text-zinc-400 hover:text-zinc-950 dark:hover:text-white text-2xl font-bold leading-none p-1 cursor-pointer print:hidden"
            >
              &times;
            </button>
          </div>

          {/* Worker Identity Card */}
          <div className="grid grid-cols-2 sm:grid-cols-4 gap-3 p-4 bg-zinc-50 dark:bg-zinc-800/60 border border-zinc-300 dark:border-zinc-700 rounded-lg text-xs mb-6">
            <div>
              <span className="text-zinc-500 dark:text-zinc-400 block text-[10px] uppercase font-bold">
                Employee
              </span>
              <strong className="text-zinc-900 dark:text-white text-sm block mt-0.5">
                {workerFullName}
              </strong>
              <span className="text-[10px] text-zinc-400">ID: {worker.id}</span>
            </div>

            <div>
              <span className="text-zinc-500 dark:text-zinc-400 block text-[10px] uppercase font-bold">
                Department &amp; Role
              </span>
              <strong className="text-zinc-900 dark:text-white block mt-0.5">
                {formatDepartment(worker.department)}
              </strong>
              <span className="text-[11px] text-zinc-600 dark:text-zinc-300">{worker.role || "Operator"}</span>
            </div>

            <div>
              <span className="text-zinc-500 dark:text-zinc-400 block text-[10px] uppercase font-bold">
                Hourly Rate
              </span>
              <strong className="text-emerald-700 dark:text-emerald-400 text-sm block mt-0.5">
                EGP {payroll.hourlyRate} / hr
              </strong>
              <span className="text-[10px] text-zinc-400">{formatEmploymentType(worker.employmentType)}</span>
            </div>

            <div>
              <span className="text-zinc-500 dark:text-zinc-400 block text-[10px] uppercase font-bold">
                Attendance Ratio
              </span>
              <strong className="text-zinc-900 dark:text-white block mt-0.5">
                {payroll.daysWorked} / {payroll.expectedWorkDays} days
              </strong>
              <span className="text-[10px] text-zinc-500">
                {payroll.expectedWorkDays > 0 ? Math.round((payroll.daysWorked / payroll.expectedWorkDays) * 100) : 0}% attendance
              </span>
            </div>
          </div>

          {/* Breakdown Section */}
          <div className="space-y-4 text-xs">
            {/* 1. Earnings */}
            <div className="border border-zinc-300 dark:border-zinc-700 rounded-lg overflow-hidden">
              <div className="bg-zinc-100 dark:bg-zinc-800 px-4 py-2 border-b border-zinc-300 dark:border-zinc-700 font-bold uppercase tracking-wider text-zinc-900 dark:text-white flex items-center justify-between">
                <span>1. Gross Earnings (المستحقات)</span>
                <span className="text-emerald-700 dark:text-emerald-400">
                  +EGP {payroll.basePay + payroll.overtimePay + payroll.allowances + payroll.manualBonuses}
                </span>
              </div>
              <div className="divide-y divide-zinc-200 dark:divide-zinc-800 p-2 text-zinc-800 dark:text-zinc-200">
                <div className="flex justify-between py-1.5 px-2">
                  <span>Regular Base Hours ({payroll.totalHours} hrs @ EGP {payroll.hourlyRate}/h)</span>
                  <span className="font-bold">EGP {payroll.basePay}</span>
                </div>
                <div className="flex justify-between py-1.5 px-2">
                  <span>
                    Overtime Pay ({payroll.overtimeHours} hrs @ 1.5x multiplier)
                  </span>
                  <span className="font-bold text-emerald-700 dark:text-emerald-400">
                    +EGP {payroll.overtimePay}
                  </span>
                </div>
                {payroll.allowances > 0 && (
                  <div className="flex justify-between py-1.5 px-2 bg-emerald-50/50 dark:bg-emerald-950/20">
                    <span>Transportation / Meal Allowances (بدلات)</span>
                    <span className="font-bold text-emerald-700 dark:text-emerald-400">
                      +EGP {payroll.allowances}
                    </span>
                  </div>
                )}
                {payroll.manualBonuses > 0 && (
                  <div className="flex justify-between py-1.5 px-2 bg-emerald-50/50 dark:bg-emerald-950/20">
                    <span>Performance &amp; Exceptional Bonuses (مكافآت)</span>
                    <span className="font-bold text-emerald-700 dark:text-emerald-400">
                      +EGP {payroll.manualBonuses}
                    </span>
                  </div>
                )}
              </div>
            </div>

            {/* 2. Deductions */}
            <div className="border border-zinc-300 dark:border-zinc-700 rounded-lg overflow-hidden">
              <div className="bg-zinc-100 dark:bg-zinc-800 px-4 py-2 border-b border-zinc-300 dark:border-zinc-700 font-bold uppercase tracking-wider text-zinc-900 dark:text-white flex items-center justify-between">
                <span>2. Deductions &amp; Advances (الاستقطاعات والسلف)</span>
                <span className="text-red-600 dark:text-red-400">
                  -EGP {payroll.absencePenalty + payroll.totalLatePenaltyEgp + payroll.salaryAdvances + payroll.manualDeductions}
                </span>
              </div>
              <div className="divide-y divide-zinc-200 dark:divide-zinc-800 p-2 text-zinc-800 dark:text-zinc-200">
                {payroll.absencePenalty > 0 ? (
                  <div className="flex justify-between py-1.5 px-2 text-red-700 dark:text-red-400">
                    <span>
                      Absence Deductions ({payroll.absentDays} unexcused day(s) @ 2x rate)
                    </span>
                    <span className="font-bold">-EGP {payroll.absencePenalty}</span>
                  </div>
                ) : (
                  <div className="flex justify-between py-1.5 px-2 text-zinc-500 italic">
                    <span>Absence Deductions (No unexcused absences)</span>
                    <span>EGP 0</span>
                  </div>
                )}

                {payroll.totalLatePenaltyEgp > 0 ? (
                  <div className="flex justify-between py-1.5 px-2 text-amber-700 dark:text-amber-400">
                    <span>
                      Late Check-in Penalties ({payroll.lateDays} late, {payroll.veryLateDays} very late)
                    </span>
                    <span className="font-bold">-EGP {payroll.totalLatePenaltyEgp}</span>
                  </div>
                ) : (
                  <div className="flex justify-between py-1.5 px-2 text-zinc-500 italic">
                    <span>Late Check-in Penalties</span>
                    <span>EGP 0</span>
                  </div>
                )}

                {payroll.salaryAdvances > 0 && (
                  <div className="flex justify-between py-1.5 px-2 bg-red-50/50 dark:bg-red-950/20 text-red-700 dark:text-red-400 font-semibold">
                    <span>Mid-month Cash Advances Recovered (سلف مستردة)</span>
                    <span className="font-bold">-EGP {payroll.salaryAdvances}</span>
                  </div>
                )}

                {payroll.manualDeductions > 0 && (
                  <div className="flex justify-between py-1.5 px-2 text-red-700 dark:text-red-400">
                    <span>Disciplinary Deductions (خصومات إدارية)</span>
                    <span className="font-bold">-EGP {payroll.manualDeductions}</span>
                  </div>
                )}
              </div>
            </div>

            {/* 3. Net Payable Summary Banner */}
            <div className="p-4 bg-emerald-50 dark:bg-emerald-950/50 border-2 border-emerald-600 rounded-lg flex flex-col sm:flex-row items-center justify-between gap-3 shadow-[3px_3px_0px_0px_#059669]">
              <div>
                <span className="text-[10px] uppercase font-bold text-emerald-800 dark:text-emerald-300 tracking-wider">
                  Net Amount Payable (صافي المستحق للصرف)
                </span>
                <p className="text-xs text-zinc-600 dark:text-zinc-400 mt-0.5">
                  Authorized for disbursement via bank transfer / cash envelope.
                </p>
              </div>
              <div className="text-right">
                <span className="text-3xl font-black font-heading text-emerald-800 dark:text-emerald-300">
                  EGP {payroll.netPayable}
                </span>
              </div>
            </div>
          </div>

          {/* Footer & Actions */}
          <div className="mt-8 pt-4 border-t-2 border-zinc-900 dark:border-zinc-700 flex flex-wrap items-center justify-between gap-3 print:hidden">
            <div className="flex gap-2">
              <button
                type="button"
                onClick={handleCopySummary}
                className="px-3.5 py-2 border-2 border-zinc-900 dark:border-zinc-700 bg-white dark:bg-zinc-800 hover:bg-zinc-100 dark:hover:bg-zinc-700 text-zinc-950 dark:text-zinc-100 font-mono text-xs font-bold uppercase tracking-wider cursor-pointer"
              >
                📋 Copy Summary
              </button>
              <button
                type="button"
                onClick={handlePrint}
                className="px-3.5 py-2 border-2 border-zinc-900 dark:border-zinc-700 bg-white dark:bg-zinc-800 hover:bg-zinc-100 dark:hover:bg-zinc-700 text-zinc-950 dark:text-zinc-100 font-mono text-xs font-bold uppercase tracking-wider cursor-pointer"
              >
                🖨️ Print Payslip
              </button>
            </div>

            <button
              type="button"
              onClick={onClose}
              className="px-5 py-2 bg-zinc-900 hover:bg-zinc-800 text-white font-mono text-xs font-bold uppercase tracking-wider border-2 border-zinc-900 cursor-pointer"
            >
              Close
            </button>
          </div>
        </div>
      </div>
    </ModalPortal>
  );
}
